-- Supabase Auth + RLS schema. Run once in the Supabase SQL Editor as a project
-- administrator. This script does not use or require a database password.

CREATE TABLE IF NOT EXISTS public.offtake_v2_suppliers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(BTRIM(name)) BETWEEN 2 AND 160),
  contact_person VARCHAR(160) NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS offtake_v2_suppliers_name_idx
  ON public.offtake_v2_suppliers (name);

CREATE TABLE IF NOT EXISTS public.offtake_v2_managers (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email VARCHAR(320) NOT NULL UNIQUE,
  full_name VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(BTRIM(full_name)) BETWEEN 2 AND 160),
  supplier_id UUID REFERENCES public.offtake_v2_suppliers(id) ON DELETE SET NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS offtake_v2_managers_supplier_idx
  ON public.offtake_v2_managers (supplier_id, is_active);

CREATE TABLE IF NOT EXISTS public.offtake_v2_admins (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email VARCHAR(320) NOT NULL UNIQUE,
  full_name VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(BTRIM(full_name)) BETWEEN 2 AND 160),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.offtake_v2_batches (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  supplier_id UUID NOT NULL REFERENCES public.offtake_v2_suppliers(id) ON DELETE RESTRICT,
  unit_quantity BIGINT NOT NULL CHECK (unit_quantity > 0),
  unit_cost_price NUMERIC(14,2) NOT NULL CHECK (unit_cost_price >= 0),
  unit_selling_price NUMERIC(14,2) NOT NULL CHECK (unit_selling_price >= 0),
  fuel_subsidy_per_unit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (fuel_subsidy_per_unit >= 0),
  total_capital NUMERIC(24,2) GENERATED ALWAYS AS (unit_quantity * unit_cost_price) STORED,
  total_revenue NUMERIC(24,2) GENERATED ALWAYS AS (unit_quantity * unit_selling_price) STORED,
  net_investor_credit NUMERIC(24,2) GENERATED ALWAYS AS
    (unit_quantity * (unit_selling_price - fuel_subsidy_per_unit - unit_cost_price)) STORED,
  destination_route VARCHAR(255) NOT NULL DEFAULT '',
  vehicle_reference VARCHAR(80) NOT NULL DEFAULT '',
  driver_name VARCHAR(160) NOT NULL DEFAULT '',
  driver_phone VARCHAR(40) NOT NULL DEFAULT '',
  status VARCHAR(16) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_transit', 'completed', 'disputed')),
  dispatched_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS offtake_v2_batches_supplier_created_idx
  ON public.offtake_v2_batches (supplier_id, created_at DESC);
CREATE INDEX IF NOT EXISTS offtake_v2_batches_status_completed_idx
  ON public.offtake_v2_batches (status, completed_at);

CREATE TABLE IF NOT EXISTS public.offtake_v2_status_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id UUID NOT NULL REFERENCES public.offtake_v2_batches(id) ON DELETE RESTRICT,
  old_status VARCHAR(16) CHECK (old_status IS NULL OR old_status IN ('pending', 'in_transit', 'completed', 'disputed')),
  new_status VARCHAR(16) NOT NULL CHECK (new_status IN ('pending', 'in_transit', 'completed', 'disputed')),
  actor_role VARCHAR(8) NOT NULL CHECK (actor_role IN ('admin', 'manager')),
  actor_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  actor_email VARCHAR(320) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS offtake_v2_audit_occurred_idx
  ON public.offtake_v2_status_audit (occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS offtake_v2_audit_batch_idx
  ON public.offtake_v2_status_audit (batch_id, occurred_at DESC);

CREATE TABLE IF NOT EXISTS public.offtake_v2_weekly_payouts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id UUID NOT NULL REFERENCES public.offtake_v2_suppliers(id) ON DELETE RESTRICT,
  week_start DATE NOT NULL,
  amount NUMERIC(24,2) NOT NULL CHECK (amount > 0),
  paid_by_admin_id UUID REFERENCES public.offtake_v2_admins(id) ON DELETE SET NULL,
  paid_by_email VARCHAR(320) NOT NULL,
  transfer_reference VARCHAR(120) NOT NULL DEFAULT '',
  paid_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS offtake_v2_payouts_period_idx
  ON public.offtake_v2_weekly_payouts (supplier_id, week_start, paid_at DESC);

