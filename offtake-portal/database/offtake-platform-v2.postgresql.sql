CREATE TRIGGER offtake_v2_auth_user_sync_email
AFTER UPDATE OF email ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.offtake_v2_sync_profile_email();

-- Provision existing email-based Supabase Auth users as managers if this schema
-- is installed after they were created. Admins must be explicitly bootstrapped.
INSERT INTO public.offtake_v2_managers (id, email, full_name)
SELECT
  u.id,
  u.email,
  CASE
    WHEN CHAR_LENGTH(BTRIM(COALESCE(u.raw_user_meta_data ->> 'full_name', ''))) >= 2
      THEN LEFT(BTRIM(u.raw_user_meta_data ->> 'full_name'), 160)
    WHEN CHAR_LENGTH(SPLIT_PART(u.email, '@', 1)) >= 2
      THEN LEFT(SPLIT_PART(u.email, '@', 1), 160)
    ELSE 'Manager'
  END
FROM auth.users AS u
WHERE u.email IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM public.offtake_v2_admins AS a WHERE a.id = u.id)
ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.offtake_v2_validate_batch_status()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_is_admin BOOLEAN;
  v_manager_supplier UUID;
  v_allowed BOOLEAN := FALSE;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NOT public.offtake_v2_is_admin() OR NEW.status <> 'pending' THEN
      RAISE EXCEPTION 'Only administrators can create pending batches.' USING ERRCODE = '42501';
    END IF;
    NEW.dispatched_at := NULL;
    NEW.completed_at := NULL;
    NEW.updated_at := now();
    RETURN NEW;
  END IF;

  IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RETURN NEW;
  END IF;

  v_is_admin := public.offtake_v2_is_admin();
  IF v_is_admin THEN
    v_allowed :=
      (OLD.status = 'pending' AND NEW.status IN ('in_transit', 'disputed'))
      OR (OLD.status = 'in_transit' AND NEW.status IN ('completed', 'disputed'))
      OR (OLD.status = 'disputed' AND NEW.status IN ('pending', 'in_transit'));
  ELSE
    v_manager_supplier := public.offtake_v2_manager_supplier_id();
    v_allowed := v_manager_supplier IS NOT NULL
      AND v_manager_supplier = OLD.supplier_id
      AND ((OLD.status = 'pending' AND NEW.status = 'in_transit')
        OR (OLD.status = 'in_transit' AND NEW.status = 'completed'));
  END IF;

  IF NOT v_allowed THEN
    RAISE EXCEPTION 'This batch status transition is not allowed.' USING ERRCODE = '42501';
  END IF;

  NEW.updated_at := now();
  IF NEW.status = 'in_transit' THEN
    NEW.dispatched_at := now();
  ELSIF NEW.status = 'pending' THEN
    NEW.dispatched_at := NULL;
  END IF;
  IF NEW.status = 'completed' THEN
    NEW.completed_at := now();
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.offtake_v2_write_status_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_actor_role TEXT;
  v_actor_email TEXT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RETURN NEW;
  END IF;
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'An authenticated actor is required.' USING ERRCODE = '42501';
  END IF;
  v_actor_role := CASE WHEN public.offtake_v2_is_admin() THEN 'admin' ELSE 'manager' END;
  SELECT email INTO v_actor_email FROM auth.users WHERE id = auth.uid();
  INSERT INTO public.offtake_v2_status_audit (
    batch_id, old_status, new_status, actor_role, actor_id, actor_email
  ) VALUES (
    NEW.id,
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
    NEW.status,
    v_actor_role,
    auth.uid(),
    COALESCE(v_actor_email, '')
  );
  RETURN NEW;
END;
$$;

